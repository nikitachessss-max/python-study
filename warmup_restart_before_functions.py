# Разминка возвращения перед сессией 5 — НЕ новая тема
#
# Цель файла:
#   вспомнить старые конструкции перед тем, как идти в свои функции def.
#
# Здесь НЕ нужны:
#   - def
#   - import
#   - классы
#   - новые библиотеки
#
# Используем только то, что уже было:
#   - input()
#   - print()
#   - if / else
#   - while True
#   - break
#   - список []
#   - append()
#   - len()
#   - for по списку
#   - total = 0.0 и total = total + число
#   - f-строка
#
# =============================================================================
# ЗАДАЧА: "Расходы за день"
# =============================================================================
#
# Сюжет:
#   Ты записываешь расходы за день.
#   Каждый расход состоит из названия и суммы.
#   Например:
#       такси — 350
#       кофе — 180
#       продукты — 1200
#
# Что должна делать программа:
#
# 1) Создать пустой список expenses.
#    В него будем складывать строки для отчёта.
#
# 2) Создать total = 0.0.
#    Это общая сумма расходов. В начале ноль.
#
# 3) Запустить бесконечный цикл:
#
#       while True:
#
# 4) Внутри цикла спросить название расхода:
#
#       name = input(...)
#
# 5) Если пользователь просто нажал Enter, то есть name == "":
#    выйти из цикла через break.
#
# 6) Если название не пустое:
#    спросить сумму расхода через float(input(...)).
#
# 7) Прибавить сумму к total.
#
# 8) Собрать строку отчёта через f-строку.
#    Например:
#
#       "кофе — 180.0 руб."
#
# 9) Добавить эту строку в список expenses через append().
#
# 10) После цикла:
#
#     Если список пустой:
#       вывести "Расходов нет."
#
#     Иначе:
#       вывести заголовок "--- Расходы ---"
#       циклом for пройти по expenses и напечатать каждую строку
#       вывести итоговую сумму total
#
# =============================================================================
# ПРОВЕРКА РУКАМИ
# =============================================================================
#
# Проверка 1:
#   Сразу нажал Enter.
#   Ожидаем: "Расходов нет."
#
# Проверка 2:
#   Ввёл:
#       кофе
#       180
#       такси
#       350
#       Enter
#   Ожидаем:
#       две строки расходов
#       итог 530.0
#
# =============================================================================
# ТИПИЧНЫЕ ОШИБКИ
# =============================================================================
#
# - Написал print(input(...)) вместо name = input(...).
#   Тогда программа спросит, но не сохранит ответ.
#
# - Забыл break.
#   Тогда пустой Enter не остановит цикл.
#
# - Забыл expenses.append(...).
#   Тогда список останется пустой.
#
# - Поставил итоговый print внутри while.
#   Тогда итог будет печататься после каждого расхода, а нужен один раз в конце.
#
# - Забыл float().
#   Тогда сумма будет текстом, а не числом.
#
# =============================================================================
# ПИШИ КОД НИЖЕ
# =============================================================================

expenses = []
total = 0.0

while True:
    name = input("Название расхода (Enter — стоп): ").strip()

    if name == "":
        break

    cost = float(input("Сумма расхода: "))
    total = total + cost

    line = f"{name} — {cost} руб."
    expenses.append(line)

if len(expenses) == 0:
    print("Расходов нет.")
else:
    print("--- Расходы ---")

    for row in expenses:
        print(row)

    print(f"Итого: {total} руб.")
